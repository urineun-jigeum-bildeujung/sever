-- review_image
CREATE TABLE review_image (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_url character varying(255) NOT NULL,
    review_id bigint NOT NULL,
    sort_order integer NOT NULL
);

-- review_question
CREATE TABLE review_question (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_answer character varying(255),
    review_id bigint NOT NULL,
    review_question_type character varying(255) NOT NULL,
    updated_at timestamp(6) with time zone,
    CONSTRAINT review_question_review_answer_check CHECK (review_answer IN ('NEGATIVE', 'NEUTRAL', 'POSITIVE')),
    CONSTRAINT review_question_review_question_type_check CHECK (review_question_type IN (
        'PALATABILITY', 'DIGESTION', 'FEEDING_CONVENIENCE', 'SKIN_COAT', 'WEIGHT_VITALITY', 'ALLERGY'
    )),
    CONSTRAINT uk_review_question_review_type UNIQUE (review_id, review_question_type)
);

-- review_recommend
CREATE TABLE review_recommend (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    review_id bigint NOT NULL,
    CONSTRAINT uk_review_recommend_member_review UNIQUE (member_id, review_id)
);

-- review_report
CREATE TABLE review_report (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    reason character varying(255),
    review_id bigint NOT NULL
);

-- product_feedback_check
CREATE TABLE product_feedback_check (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    answered_at timestamp(6) with time zone,
    check_available_at timestamp(6) with time zone,
    check_expires_at timestamp(6) with time zone,
    feedback_check_answer character varying(255),
    feedback_check_status character varying(255) NOT NULL,
    member_id bigint NOT NULL,
    order_product_id bigint NOT NULL,
    pet_id bigint,
    product_id bigint NOT NULL,
    CONSTRAINT product_feedback_check_feedback_check_answer_check CHECK (feedback_check_answer IN ('GOOD', 'NEUTRAL', 'BAD')),
    CONSTRAINT product_feedback_check_feedback_check_status_check CHECK (feedback_check_status IN ('PENDING', 'ANSWERED', 'POSTPONED')),
    CONSTRAINT uk_product_feedback_check_order_product UNIQUE (order_product_id)
);
