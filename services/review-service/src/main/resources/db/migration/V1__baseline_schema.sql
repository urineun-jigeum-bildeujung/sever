    CONSTRAINT ukgmg9jbxsicx6xd926bgq4vb5m UNIQUE (review_id, concern_code),
    CONSTRAINT fkhn6lkoq8w0acn19r98uhwyonr FOREIGN KEY (review_id) REFERENCES review(id)
