-- review
CREATE TABLE review (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    data_origin character varying(255),
    dataset_run_id bigint,
    deleted_at timestamp(6) with time zone,
    is_synthetic boolean NOT NULL,
    member_id bigint NOT NULL,
    product_id bigint NOT NULL,
    star_rate double precision NOT NULL,
    text character varying(255),
    usage_period integer NOT NULL,
    CONSTRAINT review_data_origin_check CHECK (data_origin IN ('REAL', 'SYNTHETIC')),
    CONSTRAINT uk_review_member_product UNIQUE (member_id, product_id)
);

-- review_pet (Review.pets @ElementCollection)
CREATE TABLE review_pet (
    review_id bigint NOT NULL,
    age integer NOT NULL,
    breed_id bigint NOT NULL,
    breed_size character varying(255),
    name character varying(255) NOT NULL,
    neutered boolean NOT NULL,
    pet_id bigint NOT NULL,
    sex character varying(255) NOT NULL,
    species character varying(255) NOT NULL,
    weight double precision NOT NULL,
    CONSTRAINT review_pet_breed_size_check CHECK (breed_size IN ('SMALL', 'MEDIUM', 'LARGE')),
    CONSTRAINT review_pet_sex_check CHECK (sex IN ('MALE', 'FEMALE')),
    CONSTRAINT review_pet_species_check CHECK (species IN ('DOG', 'CAT')),
    CONSTRAINT fkcl24m7cjrxmuy4oaldti7n8hx FOREIGN KEY (review_id) REFERENCES review(id)
);

